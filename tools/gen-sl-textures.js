// ------------------------------------------------------------------ PNG encode / decode (RGBA8, no interlace)
const CRC = new Uint32Array(256);
for (let n = 0; n < 256; n++) {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  CRC[n] = c >>> 0;
}
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC[(c ^ buf[i]) & 255] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}
function encodePNG(w, h, rgba) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) {
    raw[y * (w * 4 + 1)] = 0;
    rgba.copy(raw, y * (w * 4 + 1) + 1, y * w * 4, (y + 1) * w * 4);
  }
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}
// Decoder only for --check of files this script wrote (RGBA8, filter 0..4).
function decodePNG(buf) {
  let p = 8, w = 0, h = 0;
  const idat = [];
  while (p < buf.length) {
    const len = buf.readUInt32BE(p);
    const type = buf.toString('ascii', p + 4, p + 8);
    const data = buf.subarray(p + 8, p + 8 + len);
    if (type === 'IHDR') {
      w = data.readUInt32BE(0);
      h = data.readUInt32BE(4);
      if (data[8] !== 8 || data[9] !== 6) return null;
    } else if (type === 'IDAT') idat.push(data);
    p += 12 + len;
  }
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const stride = w * 4, out = Buffer.alloc(w * h * 4);
  let prev = Buffer.alloc(stride), q = 0;
  for (let y = 0; y < h; y++) {
    const f = raw[q++];
    const line = Buffer.from(raw.subarray(q, q + stride));
    q += stride;
    for (let i = 0; i < stride; i++) {
      const a = i >= 4 ? line[i - 4] : 0, b = prev[i], c = i >= 4 ? prev[i - 4] : 0;
      let v = line[i];
      if (f === 1) v += a;
      else if (f === 2) v += b;
      else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) {
        const pp = a + b - c, pa = Math.abs(pp - a), pb = Math.abs(pp - b), pc = Math.abs(pp - c);
        v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      line[i] = v & 255;
    }
    line.copy(out, y * stride);
    prev = line;
  }
  return { w, h, data: out };
}

// ------------------------------------------------------------------ colour + canvas helpers
function mulberry32(seed) {
  return function () {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function seedOf(name) {
  let s = 2166136261;
  for (const ch of name) s = Math.imul(s ^ ch.charCodeAt(0), 16777619);
  return s >>> 0;
}
const clamp = (v) => Math.max(0, Math.min(255, Math.round(v)));
const hex = (h) => [(h >> 16) & 255, (h >> 8) & 255, h & 255];
const mix = (a, b, t) => [0, 1, 2].map((i) => clamp(a[i] + (b[i] - a[i]) * t));
const add = (c, d) => c.map((v) => clamp(v + d));
const scale = (c, k) => c.map((v) => clamp(v * k));

class Canvas {
  constructor(w = 16, h = 16) {
    this.w = w;
    this.h = h;
    this.d = Buffer.alloc(w * h * 4); // transparent
  }
  set(x, y, c, a = 255) {
    x = Math.round(x);
    y = Math.round(y);
    if (x < 0 || y < 0 || x >= this.w || y >= this.h) return;
    const o = (y * this.w + x) * 4;
    const col = typeof c === 'number' ? hex(c) : c;
    if (a >= 255 || this.d[o + 3] === 0) {
      this.d[o] = col[0];
      this.d[o + 1] = col[1];
      this.d[o + 2] = col[2];
      this.d[o + 3] = a >= 255 ? 255 : a;
      return;
    }
    const t = a / 255; // blend over an opaque-ish pixel
    for (let i = 0; i < 3; i++) this.d[o + i] = clamp(this.d[o + i] * (1 - t) + col[i] * t);
    this.d[o + 3] = Math.max(this.d[o + 3], a);
  }
  get(x, y) {
    const o = (y * this.w + x) * 4;
    return [this.d[o], this.d[o + 1], this.d[o + 2], this.d[o + 3]];
  }
  alpha(x, y) {
    return this.d[(y * this.w + x) * 4 + 3];
  }
  clear(x, y) {
    this.d.fill(0, (y * this.w + x) * 4, (y * this.w + x) * 4 + 4);
  }
  each(fn) {
    for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) fn(x, y);
  }
  rect(x0, y0, x1, y1, c) {
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) this.set(x, y, c);
  }
  // Darken-outline every transparent pixel 4-adjacent to an opaque one (MC item style).
  outline(c) {
    const add = [];
    this.each((x, y) => {
      if (this.alpha(x, y)) return;
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        const nx = x + dx, ny = y + dy;
        if (nx >= 0 && ny >= 0 && nx < this.w && ny < this.h && this.alpha(nx, ny) === 255) {
          add.push([x, y]);
          break;
        }
      }
    });
    for (const [x, y] of add) this.set(x, y, c);
  }
  copyFrom(other) {
    other.d.copy(this.d);
    return this;
  }
}
// Stack frames vertically into one strip (MC animated texture).
function strip(frames) {
  const out = new Canvas(16, 16 * frames.length);
  frames.forEach((f, k) => f.d.copy(out.d, k * 16 * 16 * 4));
  return out;
}

