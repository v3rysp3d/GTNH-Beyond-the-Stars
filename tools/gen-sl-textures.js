// ------------------------------------------------------------------ write / check / preview
function mcmetaText(m) {
  return JSON.stringify(m, null, 2) + '\n';
}
function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const pi = args.indexOf('--preview');
  let drift = 0;
  for (const o of OUT) {
    const file = path.join(ROOT, o.rel);
    if (check) {
      const ok = fs.existsSync(file) && (() => {
        const got = decodePNG(fs.readFileSync(file));
        return got && got.w === o.canvas.w && got.h === o.canvas.h && got.data.equals(o.canvas.d);
      })();
      const metaOk = !o.mcmeta || (fs.existsSync(file + '.mcmeta') && fs.readFileSync(file + '.mcmeta', 'utf8') === mcmetaText(o.mcmeta));
      if (!ok || !metaOk) {
        drift++;
        console.log('DRIFT ' + o.rel);
      }
      continue;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, encodePNG(o.canvas.w, o.canvas.h, o.canvas.d));
    if (o.mcmeta) fs.writeFileSync(file + '.mcmeta', mcmetaText(o.mcmeta));
  }
  if (check) {
    console.log(drift ? drift + ' texture(s) drifted' : 'all ' + OUT.length + ' textures match');
    process.exit(drift ? 1 : 0);
  }
  console.log('wrote ' + OUT.length + ' textures under ' + ROOT);
  if (pi >= 0 && args[pi + 1]) preview(args[pi + 1]);
}
// 8x contact sheet: every texture's first frame, plus every frame of the animated ones, on a checker.
function preview(out) {
  const cells = [];
  for (const o of OUT) {
    const n = o.canvas.h / 16;
    for (let k = 0; k < n; k++) cells.push({ c: o.canvas, k });
  }
  const S = 8, cell = 16 * S + 6, cols = 8, rows = Math.ceil(cells.length / cols);
  const W = cols * cell, H = rows * cell, img = Buffer.alloc(W * H * 4);
  for (let i = 0; i < W * H; i++) {
    const x = i % W, y = (i / W) | 0, v = ((x >> 3) + (y >> 3)) & 1 ? 72 : 52;
    img[i * 4] = img[i * 4 + 1] = img[i * 4 + 2] = v;
    img[i * 4 + 3] = 255;
  }
  cells.forEach(({ c, k }, i) => {
    const ox = (i % cols) * cell + 3, oy = ((i / cols) | 0) * cell + 3;
    for (let y = 0; y < 16 * S; y++) {
      for (let x = 0; x < 16 * S; x++) {
        const s = (((k * 16 + ((y / S) | 0)) * 16) + ((x / S) | 0)) * 4, d = ((oy + y) * W + ox + x) * 4;
        const a = c.d[s + 3] / 255;
        for (let j = 0; j < 3; j++) img[d + j] = clamp(c.d[s + j] * a + img[d + j] * (1 - a));
      }
    }
  });
  fs.writeFileSync(out, encodePNG(W, H, img));
  console.log('preview ' + out);
}
main();
