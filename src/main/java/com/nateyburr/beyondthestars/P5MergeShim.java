package com.nateyburr.beyondthestars;

import net.minecraftforge.fluids.FluidRegistry;

import com.nateyburr.beyondthestars.items.SLP5Items;

import gregtech.api.enums.FluidState;
import gregtech.api.fluid.GTFluidFactory;

/**
 * MERGE SHIM (p5-eye only; DROP AT MERGE together with {@code items/SLP5Items.java} and its one call in
 * {@code CommonProxy.preInit}). p5-content registers the P5 items ({@code SLP5Items}) and the fluids
 * {@code btsdarkmatter} / {@code btsentangleddarkmatter} ({@code SLRealityFluids.darkMatter}); until that branch is
 * merged, this registers stand-ins under the same registry names so the Eye's T9 / T10 code runs on the dev server.
 * The Eye reads the fluid by its registry name ({@code EyeP5Fluids}), so it needs no change at the merge.
 */
public final class P5MergeShim {

    private P5MergeShim() {}

    /** preInit, after the items and fluids of the other phases. */
    public static void register() {
        SLP5Items.register();
        if (FluidRegistry.getFluid("btsdarkmatter") == null) {
            GTFluidFactory.builder("btsdarkmatter")
                .withDefaultLocalName("Attractor Dark Matter")
                .withTextureName("molten.autogenerated")
                .withColorRGBA(new short[] { 40, 20, 70, 240 })
                .withStateAndTemperature(FluidState.LIQUID, 2)
                .buildAndRegister()
                .addLocalizedName();
            BeyondTheStars.LOG.info("[BTS] P5 merge shim: btsdarkmatter registered (p5-content owns it)");
        }
    }
}
