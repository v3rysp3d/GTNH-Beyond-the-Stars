package com.nateyburr.beyondthestars.fluids;

import net.minecraftforge.fluids.Fluid;

import gregtech.api.enums.FluidState;

/**
 * D-26 PROPELLANT AND COOLANT LINE FLUIDS (S4). Owned by <b>Track C (Propellant + Coolant)</b> -
 * both of that track's lines register here, because both are one track's and a second file would
 * buy nothing but a second thing to keep in step.
 * <p>
 * <b>The six ladder rungs are NOT here and must not be moved.</b>
 * {@code BTSFluids.naqPropellantT1..T6} keep their fields, their registry names and their D-08 P
 * values exactly as they are. P-01 to P-03h only make the INPUT side of those six longer - three
 * real stages (an oxidiser, a metallised slurry, a blend) instead of one Mixer step - and P-03
 * still emits 250 L per cycle, so the Spiral chamber's supply-rate-against-clock-frequency
 * balance from D-20 is untouched.
 * <p>
 * <b>Three slurries, not six.</b> P-02 lists exactly three metals - Aluminium for Lv 1-2,
 * Adamantium for Lv 3-4, Infinity for Lv 5-6 - so six rung-numbered slurries would have meant two
 * pairs of fluids that are the same milled metal under different names. The fluid carries the
 * METAL, the recipe carries the rung:
 *
 * <pre>
 *   Lv 1, Lv 2  -> metalSlurryAluminium   (aluminised propellant, the textbook case)
 *   Lv 3, Lv 4  -> metalSlurryAdamantium
 *   Lv 5, Lv 6  -> metalSlurryInfinity
 * </pre>
 */
public final class BTSFluidsPropellant {

    /** P-01 out: nitric acid conditioned with dinitrogen tetroxide. The oxidiser half. */
    public static Fluid oxidiserBlend;
    /** P-02 out, Lv 1-2: aluminium milled into kerosene for density impulse. */
    public static Fluid metalSlurryAluminium;
    /** P-02 out, Lv 3-4. */
    public static Fluid metalSlurryAdamantium;
    /** P-02 out, Lv 5-6. */
    public static Fluid metalSlurryInfinity;
    /**
     * C-04 out: a real PWR boric-acid / lithium-hydroxide chemical shim, used by C-02 and C-03 as
     * a corrosion inhibitor. It is a COOLANT-MANUFACTURING reagent and is never fed to the
     * reactor - the D-08 coolant ladder is a settled table of six existing pack fluids and this
     * is not a seventh rung.
     */
    public static Fluid chemicalShim;

    private BTSFluidsPropellant() {}

    public static void register() {
        oxidiserBlend = build("btsoxidiserblend", "Oxidiser Blend", 235, 150, 60, 300, FluidState.LIQUID);
        metalSlurryAluminium = build(
            "btsmetalslurryaluminium",
            "Metal Additive Slurry (Aluminium)",
            190,
            195,
            205,
            310,
            FluidState.SLURRY);
        metalSlurryAdamantium = build(
            "btsmetalslurryadamantium",
            "Metal Additive Slurry (Adamantium)",
            200,
            120,
            120,
            330,
            FluidState.SLURRY);
        metalSlurryInfinity = build(
            "btsmetalslurryinfinity",
            "Metal Additive Slurry (Infinity)",
            245,
            240,
            220,
            360,
            FluidState.SLURRY);
        chemicalShim = build("btschemicalshim", "Chemical Shim", 150, 200, 235, 300, FluidState.LIQUID);
    }

    private static Fluid build(String name, String localName, int r, int g, int b, int kelvin, FluidState state) {
        return gregtech.api.fluid.GTFluidFactory.builder(name)
            .withDefaultLocalName(localName)
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { (short) r, (short) g, (short) b, (short) 240 })
            .withStateAndTemperature(state, kelvin)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();
    }
}
