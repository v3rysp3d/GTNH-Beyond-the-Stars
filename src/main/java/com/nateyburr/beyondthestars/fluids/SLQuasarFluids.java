package com.nateyburr.beyondthestars.fluids;

import net.minecraftforge.fluids.Fluid;

import gregtech.api.enums.FluidState;
import gregtech.api.fluid.GTFluidFactory;

/**
 * P4 fluids (design repo {@code designs/docs/quasar-p4.md} §6.2, rev 7f91607; D-50). Called from one appended line in
 * {@link BTSFluids#register()}, BEFORE {@link SLRealityFluids#register()}: the Homogeny / Reality recipes used to
 * register these two names as placeholders (question H-24), and now read P4's fluids instead.
 * <ul>
 * <li><b>Ergomatter</b> ({@code btsergomatter}): Eye T7's product (Triangulum, 600 L a cycle x Y x r x min(beta,
 * 1.5)), Eye T8's feed (0-10 L/s), the throats' fuel after T7, and the gate fluid of every T7 -> T8 part.</li>
 * <li><b>Superdense Ergomatter</b> ({@code btssuperdenseergomatter}): one fluid whichever route made it (Q-13): Eye
 * T8 makes it 1 : 1 from its Ergomatter feed, and the Kerr Compressor module refines it 8 : 1 on its DENSITY map
 * (SL-Q23). Renamed from "Supermassive Ergomatter" by ruling 17.</li>
 * </ul>
 * The registry names were frozen by the Homogeny / Reality branch (they are in saved tanks there), so they are kept
 * exactly; the colours match the placeholders. Both use GT's tinted {@code molten.autogenerated} texture like every
 * Singularity Ladder fluid, so nothing renders purple/black.
 */
public final class SLQuasarFluids {

    /** Eye T7 (Triangulum) output; Eye T8's feed; the conduit throats' fuel after T7. */
    public static Fluid ergomatter;
    /** Eye T8 (Milky Way) output, or Ergomatter refined 8 : 1 on the Kerr's DENSITY map (SL-Q23). */
    public static Fluid superdenseErgomatter;

    private SLQuasarFluids() {}

    public static void register() {
        ergomatter = liquid("btsergomatter", "Ergomatter", 63, 210, 180, 0);
        superdenseErgomatter = liquid("btssuperdenseergomatter", "Superdense Ergomatter", 31, 143, 128, 0);
    }

    private static Fluid liquid(String name, String localName, int r, int g, int b, int kelvin) {
        return GTFluidFactory.builder(name)
            .withDefaultLocalName(localName)
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { (short) r, (short) g, (short) b, (short) 240 })
            .withStateAndTemperature(FluidState.LIQUID, kelvin)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();
    }
}
