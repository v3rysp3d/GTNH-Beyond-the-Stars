package com.nateyburr.beyondthestars.fluids;

import java.util.HashSet;
import java.util.Set;

import net.minecraftforge.fluids.Fluid;
import net.minecraftforge.fluids.FluidRegistry;

import com.nateyburr.beyondthestars.BeyondTheStars;

import gregtech.api.enums.FluidState;
import gregtech.api.fluid.GTFluidFactory;

/**
 * SINGULARITY LADDER fluids of the Homogeny and the Reality machines (design repo
 * {@code designs/docs/homogeny-reality.md} §4.4 and §5.1, PROPOSED). Called from one appended line in
 * {@link BTSFluids#register()}, after {@link SLFluids#register()}. Field names follow the doc; the registry names are
 * frozen once shipped (a tank in a saved world holds the name).
 * <ul>
 * <li>Two Homogeny products: Degenerate Stellar Mixture (T2) and Entanglement Medium (T3).</li>
 * <li>Six Entangled Region condensates, made only by Reality Diffraction and drawn back out by Reality Refab.</li>
 * <li>Five addon condensates (SL-B16, SL-C01..C04), the BEC proposal's pattern: one GAS fluid at 0 K per source,
 * tinted like the source at alpha 200; their generator recipes live with the recipes, not here.</li>
 * <li>Ergomatter and Superdense Ergomatter are P4's ({@link SLQuasarFluids}, registered just before this file):
 * the fields below are aliases of P4's, kept so the Homogeny / Reality code reads the same. White Hole Matter (P5) is
 * still registered here under its planned name only if nothing registered it first, so the recipes that need it are
 * present in NEI but unreachable until an Eye makes it (question H-24). Whoever merges P5 must make one owner of it
 * (question H/R-4).</li>
 * </ul>
 * Every fluid uses GT's tinted {@code molten.autogenerated} texture, as SLFluids does, so nothing renders purple/black.
 */
public final class SLRealityFluids {

    // ---- Homogeny products
    /** Homogeny T2+ (SL-H11): White + Black Dwarf Matter in Excited Stellar Plasma Mixture. */
    public static Fluid degenerateStellarMixture;
    /** Homogeny T3 (SL-H21): the medium Reality Diffraction splits. */
    public static Fluid entanglementMedium;

    // ---- the six Entangled Regions (Reality Diffraction out, Reality Refab in), index = region - 1
    public static Fluid regionHyperspace;
    public static Fluid regionSubspace;
    public static Fluid regionForwardTime;
    public static Fluid regionReverseTime;
    public static Fluid regionPositiveMass;
    public static Fluid regionNegativeMass;

    // ---- addon condensates (Condensate Generator, 1 : 1)
    /** SL-B16, the BEC proposal's reserved slot: Magnetar Matter 144 L -> 144 L. */
    public static Fluid entangledMagnetar;
    /** SL-C01: Degenerate Stellar Mixture 1,000 L -> 1,000 L. */
    public static Fluid entangledDegenerate;
    /** SL-C02: Ergomatter 1,000 L -> 1,000 L. */
    public static Fluid entangledErgomatter;
    /** SL-C03: Superdense Ergomatter 1,000 L -> 1,000 L. */
    public static Fluid entangledSuperdense;
    /** SL-C04: White Hole Matter 144 L -> 144 L. */
    public static Fluid entangledWhiteHole;

    // ---- P4's fluids (aliases of SLQuasarFluids) and a later phase's, registered only if absent (H-24)
    /** Eye T7 output: {@link SLQuasarFluids#ergomatter}. */
    public static Fluid ergomatter;
    /** Eye T8 output, or refined from Ergomatter on the Kerr: {@link SLQuasarFluids#superdenseErgomatter}. */
    public static Fluid superdenseErgomatter;
    /** Eye T9 output (P5). */
    public static Fluid whiteHoleMatter;

    /** The later phases' fluids this file registered itself (no Eye makes them yet): the recipe unit's gate log. */
    private static final Set<Fluid> PLACEHOLDERS = new HashSet<>();

    private SLRealityFluids() {}

    /**
     * True if {@code fluid} is one of the later phases' fluids that only this file registered (H-24): every recipe
     * that needs it is present in NEI but cannot be run until an Eye tier makes it. False once P4/P5 own it.
     */
    public static boolean isPlaceholder(Fluid fluid) {
        return fluid != null && PLACEHOLDERS.contains(fluid);
    }

    public static void register() {
        degenerateStellarMixture = fluid(
            "btsdegeneratestellarmixture",
            "Degenerate Stellar Mixture",
            200,
            208,
            255,
            240,
            FluidState.LIQUID,
            1_000_000);
        entanglementMedium = fluid(
            "btsentanglementmedium",
            "Entanglement Medium",
            240,
            224,
            255,
            240,
            FluidState.LIQUID,
            0);

        regionHyperspace = condensate("btsregionhyperspace", "Entangled Region I: Hyperspace", 150, 90, 255);
        regionSubspace = condensate("btsregionsubspace", "Entangled Region II: Subspace", 60, 200, 255);
        regionForwardTime = condensate("btsregionforwardtime", "Entangled Region III: Forward Time", 255, 210, 70);
        regionReverseTime = condensate("btsregionreversetime", "Entangled Region IV: Reverse Time", 255, 80, 200);
        regionPositiveMass = condensate("btsregionpositivemass", "Entangled Region V: Positive Mass", 220, 40, 50);
        regionNegativeMass = condensate("btsregionnegativemass", "Entangled Region VI: Negative Mass", 245, 245, 255);

        // P4 owns these two now (SLQuasarFluids, registered first): no placeholder, so no gate line.
        ergomatter = SLQuasarFluids.ergomatter;
        superdenseErgomatter = SLQuasarFluids.superdenseErgomatter;
        whiteHoleMatter = ifAbsent(
            "btswhiteholematter",
            "White Hole Matter",
            255,
            246,
            224,
            FluidState.LIQUID,
            100_000_000);

        entangledMagnetar = condensate("btsentangledmagnetar", "Entangled Magnetar Matter", 214, 40, 140);
        entangledDegenerate = condensate(
            "btsentangleddegenerate",
            "Entangled Degenerate Stellar Mixture",
            200,
            208,
            255);
        entangledErgomatter = condensate("btsentangledergomatter", "Entangled Ergomatter", 63, 210, 180);
        entangledSuperdense = condensate("btsentangledsuperdense", "Entangled Superdense Ergomatter", 31, 143, 128);
        entangledWhiteHole = condensate("btsentangledwhitehole", "Entangled White Hole Matter", 255, 246, 224);
    }

    /** The six regions in order (I..VI), as Reality Diffraction outputs them and Reality Refab draws them. */
    public static Fluid[] regions() {
        return new Fluid[] { regionHyperspace, regionSubspace, regionForwardTime, regionReverseTime, regionPositiveMass,
            regionNegativeMass };
    }

    /** A condensate in GT's style: GAS at 0 K, alpha 200. */
    private static Fluid condensate(String name, String localName, int r, int g, int b) {
        return fluid(name, localName, r, g, b, 200, FluidState.GAS, 0);
    }

    /** A later phase's fluid: reuse it if its owner registered it first, else register it here under the same name. */
    private static Fluid ifAbsent(String name, String localName, int r, int g, int b, FluidState state, int kelvin) {
        final Fluid existing = FluidRegistry.getFluid(name);
        if (existing != null) {
            BeyondTheStars.LOG.info("[BTS] " + name + " is already registered; the Reality recipes use it.");
            return existing;
        }
        BeyondTheStars.LOG.info(
            "[BTS] " + name
                + " registered as a placeholder (its Eye tier is not built yet): its recipes are unreachable.");
        final Fluid placeholder = fluid(name, localName, r, g, b, 240, state, kelvin);
        PLACEHOLDERS.add(placeholder);
        return placeholder;
    }

    private static Fluid fluid(String name, String localName, int r, int g, int b, int a, FluidState state,
        int kelvin) {
        return GTFluidFactory.builder(name)
            .withDefaultLocalName(localName)
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { (short) r, (short) g, (short) b, (short) a })
            .withStateAndTemperature(state, kelvin)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();
    }
}
