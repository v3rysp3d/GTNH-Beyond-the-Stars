package com.nateyburr.beyondthestars.fluids;

import net.minecraftforge.fluids.Fluid;

import gregtech.api.enums.FluidState;
import gregtech.api.fluid.GTFluidFactory;

/**
 * BEC EXPANSION condensates, SL-B10..SL-B15 (designs/docs/bec-expansion-proposal.md §4; ruling 11b). Called
 * from one appended line in {@link BTSFluids#register()}.
 * <p>
 * GT 2.9.0-RC-2's Bose-Einstein Condensate network is fluid-generic: the Condensate Generator turns any fluid that
 * has a recipe in {@code TecTechRecipeMaps.condensateGeneratorRecipes} into whatever that recipe outputs, and the
 * network, the Containment Field and the Condensate Assembler's nodes key everything by {@code Fluid}. GT's own 19
 * condensates are an enum we cannot extend, so an addon condensate is one registered fluid plus one generator recipe
 * ({@code BTSRecipesBEC.condensates()}). Each is a GAS at 0 K like GT's own, with GT's tinted molten texture (no
 * purple/black). Names are frozen once shipped: a Containment Field in a saved world holds them.
 * <p>
 * The reserved SL-B16 (Entangled Magnetar Matter, {@code btsentangledmagnetar}) is not registered here: its first
 * consumers are P4's and the Homogeny/Reality branch registers it with them (proposal Q-B6).
 */
public final class SLCondensates {

    /** SL-B10: Raw Star Matter (Eye T1, Sol), 1,000 L unit. Family S1 "Stellar". */
    public static Fluid entangledStarMatter;
    /** SL-B11: Excited Stellar Plasma Mixture (Eye T2), 1,000 L unit. Family S1. */
    public static Fluid entangledExcitedPlasma;
    /** SL-B12: Hyperdense Stellar Mixture (Kerr T2 on Eye T3's raw plasma), 1,000 L unit. Families S1 and S2. */
    public static Fluid entangledHyperdense;
    /** SL-B13: White Dwarf Matter (Eye T4), 144 L unit. Family S2 "Remnant". */
    public static Fluid entangledWhiteDwarf;
    /** SL-B14: Black Dwarf Matter (Eye T5), 144 L unit. Family S2. */
    public static Fluid entangledBlackDwarf;
    /** SL-B15: Antipolarization Agent (pre-Eye chemistry, used from Eye T6), 1,000 L unit. Family S2. */
    public static Fluid entangledAgent;

    private SLCondensates() {}

    public static void register() {
        entangledStarMatter = condensate("btsentangledstarmatter", "Entangled Raw Star Matter", 186, 120, 255);
        entangledExcitedPlasma = condensate(
            "btsentangledexcitedplasma",
            "Entangled Excited Stellar Plasma",
            255,
            194,
            58);
        entangledHyperdense = condensate("btsentangledhyperdense", "Entangled Hyperdense Stellar Mixture", 154, 26, 58);
        entangledWhiteDwarf = condensate("btsentangledwhitedwarf", "Entangled White Dwarf Matter", 236, 240, 255);
        entangledBlackDwarf = condensate("btsentangledblackdwarf", "Entangled Black Dwarf Matter", 44, 36, 64);
        entangledAgent = condensate("btsentangledantipolarization", "Entangled Antipolarization Agent", 120, 230, 255);
    }

    /**
     * The condensate's unit in litres (GT's {@code CondensateType} convention): 144 for the molten metals, 1,000 for
     * the fluids. Recipe amounts must be multiples of half of it. 0 for a fluid that is not one of ours.
     */
    public static int unitOf(Fluid fluid) {
        if (fluid == null) return 0;
        if (fluid == entangledWhiteDwarf || fluid == entangledBlackDwarf) return 144;
        if (fluid == entangledStarMatter || fluid == entangledExcitedPlasma
            || fluid == entangledHyperdense
            || fluid == entangledAgent) return 1_000;
        return 0;
    }

    /**
     * GT's condensate style: GAS at 0 K, alpha 200, the tinted molten texture. The one condensate registrar;
     * {@link SLRealityFluids} registers its condensates through it too.
     */
    static Fluid condensate(String name, String localName, int r, int g, int b) {
        return GTFluidFactory.builder(name)
            .withDefaultLocalName(localName)
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { (short) r, (short) g, (short) b, (short) 200 })
            .withStateAndTemperature(FluidState.GAS, 0)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();
    }
}
