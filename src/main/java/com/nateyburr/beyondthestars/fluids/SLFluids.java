package com.nateyburr.beyondthestars.fluids;

import net.minecraftforge.fluids.Fluid;

import gregtech.api.enums.FluidState;
import gregtech.api.fluid.GTFluidFactory;

/**
 * SINGULARITY LADDER fluids (singularity-ladder-build.md §1.1). Owned by the Foundation unit;
 * called from one appended line in {@link BTSFluids#register()}.
 * <p>
 * Only the three stellar intermediates are new. Raw Stellar Plasma Mixture is the pack's
 * {@code Materials.RawStarMatter} (Q-1), and White / Black Dwarf Matter are GT materials. The
 * internal names are frozen once shipped: a fluid's name is what a tank in a saved world holds.
 */
public final class SLFluids {

    /** Eye T2 (Sirius A) output; Eye T3's star input. */
    public static Fluid excitedStellarPlasma;
    /** Eye T3 (Arcturus) output; the Kerr's densify input. */
    public static Fluid rawHyperdensePlasma;
    /** Kerr T2 densify output; the Eye T4 gate. */
    public static Fluid hyperdenseStellarMixture;

    // ---- D-49 star lifecycle (d49-build-plan.md §9, star-lifecycle.md §5). Appended; names frozen once shipped.
    /** Attuned Tengam + Semi-Stable Antimatter + SpaceTime (LCR, SL-S01); frozen into the Agent. */
    public static Fluid positronicTengamSlurry;
    /** The magnetar's constant feed and its flare-shield trim (Eye T6); SL-S02. */
    public static Fluid antipolarizationAgent;
    /** Eye T6 (SGR 1806-20) output. No consumer until P5 (plan §17 item 12). */
    public static Fluid magnetarMatter;

    private SLFluids() {}

    public static void register() {
        excitedStellarPlasma = liquid(
            "btsexcitedstellarplasma",
            "Excited Stellar Plasma Mixture",
            255,
            194,
            58,
            50_000);
        rawHyperdensePlasma = liquid("btsrawhyperdenseplasma", "Raw Hyperdense Stellar Plasma", 210, 72, 42, 80_000);
        hyperdenseStellarMixture = liquid(
            "btshyperdensestellarmixture",
            "Hyperdense Stellar Mixture",
            154,
            26,
            58,
            120_000);

        positronicTengamSlurry = liquid("btspositronictengamslurry", "Positronic Tengam Slurry", 196, 92, 214, 2_000);
        antipolarizationAgent = liquid("btsantipolarizationagent", "Antipolarization Agent", 120, 230, 255, 4);
        magnetarMatter = liquid("btsmagnetarmatter", "Magnetar Matter", 214, 40, 140, 10_000_000);
    }

    /** Same shape as {@code BTSFluidsProcess.build}: GT's tinted molten texture, no PNG needed. */
    private static Fluid liquid(String name, String localName, int r, int g, int b, int kelvin) {
        return GTFluidFactory.builder(name)
            .withDefaultLocalName(localName)
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { (short) r, (short) g, (short) b, (short) 240 })
            .withStateAndTemperature(FluidState.LIQUID, kelvin)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();
    }
}
