package com.nateyburr.beyondthestars.fluids;

import net.minecraftforge.fluids.Fluid;

import gregtech.api.enums.FluidState;
import gregtech.api.fluid.GTFluidFactory;

public final class BTSFluids {

    public static Fluid nuclearWasteWater;
    public static Fluid naqPropellantT1;
    public static Fluid naqPropellantT2;
    public static Fluid naqPropellantT3;

    private BTSFluids() {}

    public static void register() {
        nuclearWasteWater = GTFluidFactory.builder("nuclearwastewater")
            .withDefaultLocalName("Nuclear Waste Water")
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { 96, 140, 60, 220 })
            .withStateAndTemperature(FluidState.LIQUID, 320)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();

        naqPropellantT1 = GTFluidFactory.builder("naqpropellant1")
            .withDefaultLocalName("Naquadah Propellant Mk I")
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { 70, 200, 90, 240 })
            .withStateAndTemperature(FluidState.LIQUID, 400)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();

        naqPropellantT2 = GTFluidFactory.builder("naqpropellant2")
            .withDefaultLocalName("Naquadah Propellant Mk II")
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { 120, 220, 70, 240 })
            .withStateAndTemperature(FluidState.LIQUID, 500)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();

        naqPropellantT3 = GTFluidFactory.builder("naqpropellant3")
            .withDefaultLocalName("Naquadah Propellant Mk III")
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { 190, 240, 60, 240 })
            .withStateAndTemperature(FluidState.LIQUID, 650)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();
    }
}
