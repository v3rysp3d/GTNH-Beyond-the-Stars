package com.nateyburr.beyondthestars.fluids;

import net.minecraftforge.fluids.Fluid;

import gregtech.api.enums.FluidState;
import gregtech.api.fluid.GTFluidFactory;

public final class BTSFluids {

    public static Fluid nuclearWasteWater;

    private BTSFluids() {}

    public static void register() {
        nuclearWasteWater = GTFluidFactory.builder("nuclearwastewater")
            .withDefaultLocalName("Nuclear Waste Water")
            .withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { 96, 140, 60, 220 })
            .withStateAndTemperature(FluidState.LIQUID, 320)
            .buildAndRegister()
            .addLocalizedName()
            .asFluid();
    }
}
