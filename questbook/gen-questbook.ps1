#   1. a retrieval gate may only name parts the player is holding AT THAT POINT on the path -
#      so the rewards must add up to the count the next gate asks for (injectors: 4 + 4 = 8);
#   2. if the step installs those parts, its DONE WHEN says HOLD, CLAIM, THEN INSTALL, and the
#      world-state check that used to be the DONE WHEN moves to its own CHECK YOUR WORK block.
