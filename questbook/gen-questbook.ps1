function B64Id([long]$high, [long]$low) {
    $b = New-Object byte[] 16
    for ($i = 0; $i -lt 8; $i++) {
        $b[7 - $i] = ($high -shr (8 * $i)) -band 0xFF
        $b[15 - $i] = ($low -shr (8 * $i)) -band 0xFF
    }
    [Convert]::ToBase64String($b)
}

function SafeLow([long]$startLow) {
    $low = $startLow
    while ((B64Id $HIGH $low) -match '[+/]') { $low++ }
    $low
}

# File-name stem. Formatting tokens are dropped FIRST, so a coloured quest name still
# yields a readable file name instead of one starting with its colour codes.
function NamePrefix([string]$name) {
    $clean = ($name -replace '\{[0-9a-fk-or]\}', '')
    $clean = ($clean -replace '[^A-Za-z0-9]', '')
    if ($clean.Length -gt 16) { $clean = $clean.Substring(0, 16) }
    $clean
}

# {6} {l} {r} ... -> the Minecraft section sign plus that code. See the header note.
$SECTION = [string][char]0xA7
function Fmt([string]$s) {
    [regex]::Replace($s, '\{([0-9a-fk-or])\}', { param($m) $SECTION + $m.Groups[1].Value })
}

function Icon([string]$id, [int]$damage, [int]$count) {
    [ordered]@{ 'Count:3' = $count; 'Damage:2' = $damage; 'OreDict:8' = ''; 'id:8' = $id }
}

