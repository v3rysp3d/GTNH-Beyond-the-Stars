# Generates the "Beyond the Stars" BetterQuesting quest-line overlay in GTNH 2.9.0's
# split DefaultQuests format (QuestLines/<line>/ placements + QuestLine.json, and
# Quests/<line>/<quest>.json). Run from this folder:  powershell -File gen-questbook.ps1
# Output goes to .\DefaultQuests\ ; merge per README.md.
#
# Also emits ONE entry quest into the pack's own "How to Generate Power" chapter:
# only ADDED files, never a modified pack file.
#
# IDs use questIDHigh = 190 (non-zero) so they can never collide with pack quests
# (which all use high 0). HIGH must stay <= 255: its byte then sits alone in a base64
# triple whose characters are provably never '+' or '/', so filenames stay legal.
# Lows are auto-advanced past any value whose base64 would contain '+' or '/'.
#
# LOW BUDGET: the chapter owns 48000..48019 (20 quests). 48020 is the pack-line entry
# quest "Unit One" and must stay where it is - a world that already ran /btsquests
# install holds it under that id, and moving it would orphan a duplicate icon inside
# a pack chapter we are not allowed to edit. BQBridge.LAST_QUEST_LOW mirrors 48019.
#
# ---------------------------------------------------------------------------------
# FORMATTING. This file is ASCII-only on purpose: Windows PowerShell 5.1 reads a .ps1
# without a BOM as Windows-1252, so a literal section sign typed as UTF-8 would come
# back as mojibake. Descriptions therefore write formatting codes as {6} {l} {r} ...
# and Fmt() turns each into the real section sign at generation time.
#
# It is also why no DONE WHEN quotes a panel fragment containing the middle dot the
# instrument panel uses as a separator: every quoted string below is the ASCII part of
# a line, checked character for character against the formatter that prints it.
#
# DIAGRAMS. BetterQuesting 3.8.x-GTNH renders images inside a quest description with
#     [img height=N]domain:path/to/file.png[/img]
# (GuiQuest.img = \[img height=([1-9]\d*)] *(.*?:.*?) *\[/img], one tag per line; the
# panel is drawn at the description canvas's width with the aspect maintained, and a
# texture that fails to load degrades to a 1x1 rect rather than crashing). The three
# diagrams are generated by gen-diagrams.ps1 into .\resources\btsquests\..., which
# merges into <instance>/config/betterquesting/resources/ - BetterQuesting registers
# that folder as a resource pack (betterquesting.misc.QuestResourcesFolder), so the
# domain name is the folder name and MUST be lowercase.
#
# BILLS OF MATERIALS. Every count in the five Blueprint quests is DERIVED, never typed:
# gen-bom.ps1 re-implements the structure shape functions, tallies each cell through the
# element table, and guards itself against the Java changing underneath it. Edit a shape
# in MTEReactorCoreMk1 and the next run either prints the new numbers or fails loudly.
# Every registry id below was verified against the GTNH 2.9.0-beta-1 sources
# (gregtech/api/casing/Casings.java, MetaTileEntityIDs.java, BlockConcretes/BlockReinforced)
# or against the pack's own quest files.

