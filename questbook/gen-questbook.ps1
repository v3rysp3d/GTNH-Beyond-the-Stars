# Every icon / task / reward stack must be a REAL stack. Icon takes (id, damage, count) and
# dropping the last argument silently yields Count 0 - a retrieval task that can never be
# completed and a reward that hands over nothing. Caught here rather than in game.
function AssertStacks($q) {
    foreach ($group in @('Icon', 'Task', 'Reward')) {
        if (-not $q.ContainsKey($group)) { continue }
        $value = $q[$group]
        if ($null -eq $value -or $value -is [string]) { continue }
        foreach ($stack in @($value)) {
            if ([string]::IsNullOrEmpty($stack['id:8'])) {
                throw "Quest '$($q.Key)' has a $group stack with no id - check the Icon call's arguments."
            }
            if ($stack['Count:3'] -lt 1) {
                throw "Quest '$($q.Key)' has a $group stack of $($stack['id:8']) with Count $($stack['Count:3']) - Icon takes (id, damage, count), so a missing count lands here."
            }
        }
    }
}

# A description must never ship an un-substituted bill placeholder or a stray PowerShell
# sigil: an interpolation that silently produced nothing is exactly how the last five
# bills went stale.
function AssertDesc($q) {
    if ($q.Desc -match '\$\(' -or $q.Desc -match '\$BTS_BOM') {
        throw "Quest '$($q.Key)' description contains an un-interpolated expression - it was written in single quotes but needs double."
    }
    if ($q.Desc -match '(?<![0-9])0x\b') {
        throw "Quest '$($q.Key)' description asks for a count of 0 - a bill lookup missed its item name."
    }
}

