# 3.8.70-GTNH that is NOT a "you once had it" flag while the task is still incomplete:
# TaskRetrieval$Detector's constructor, on the !consume path, zeroes every required-item entry
# whose progress is BELOW its required count, then re-counts from the live inventory
# (InventoryPlayer.getStackInSlot over getSizeInventory(), so worn ARMOUR counts too). An entry
# only latches once it has been seen at its FULL count at one instant, and TaskRetrieval.detect
# returns immediately for a task that is already complete - so a completed step never comes
# undone, but PARTIAL progress never accumulates.
#
