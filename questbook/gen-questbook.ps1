function QuestJson($q) {
    # prerequisites: in-line keys plus raw (high, low) pairs from outside this line
    $pre = [ordered]@{}
    $pi = 0
    foreach ($pk in $q.Prereqs) {
        $pre["${pi}:10"] = [ordered]@{ 'questIDHigh:4' = $HIGH; 'questIDLow:4' = $byKey[$pk].Low }
        $pi++
    }
    if ($q.RawPrereqs) {
        foreach ($rp in $q.RawPrereqs) {
            $pre["${pi}:10"] = [ordered]@{ 'questIDHigh:4' = [long]$rp.High; 'questIDLow:4' = [long]$rp.Low }
            $pi++
        }
    }

    # task: a checkbox, or a retrieval of one or more stacks. consume/autoConsume stay 0
    # everywhere on purpose - a step that gated on the controller and then ATE it would
    # brick the plant the player just built.
    if ($q.Task -is [string]) {
        $task = [ordered]@{ 'index:3' = 0; 'taskID:8' = 'bq_standard:checkbox' }
    } else {
        $items = [ordered]@{}
        $ii = 0
        foreach ($it in @($q.Task)) {
            $items["${ii}:10"] = $it
            $ii++
        }
        $task = [ordered]@{
            'autoConsume:1'        = 0; 'consume:1' = 0; 'groupDetect:1' = 0; 'ignoreNBT:1' = 1
            'index:3'              = 0; 'partialMatch:1' = 1; 'requireOnlyOneItem:1' = 0
            'requiredItems:9'      = $items
            'taskID:8'             = 'bq_standard:retrieval'
        }
    }

    # rewards: one bq_standard:item entry per stack, so a stack-size-1 item (the Turbine
    # Rotor) is never handed out as an illegal stack.
    $rewards = [ordered]@{}
    $ri = 0
    if ($q.Reward) {
        foreach ($rw in @($q.Reward)) {
            $rewards["${ri}:10"] = [ordered]@{
                'ignoreDisabled:1' = 0
                'index:3'          = $ri
                'rewardID:8'       = 'bq_standard:item'
                'rewards:9'        = [ordered]@{ '0:10' = $rw }
            }
            $ri++
        }
    }

    $countAs = if ($q.ContainsKey('CountAs')) { $q.CountAs } else { 1 }

    [ordered]@{
        'preRequisites:9' = $pre
        'properties:10'   = [ordered]@{
            'betterquesting:10' = [ordered]@{
                'autoClaim:1'             = 0
                'completion_animation:8'  = 'default'
                'completion_particle:8'   = 'default'
                'confetti_icon:10'        = (Icon 'minecraft:stick' 0 0)
                'countAsQuest:1'          = $countAs
                'desc:8'                  = (Fmt $q.Desc)
                'globalShare:1'           = 1
                'icon:10'                 = $q.Icon
                'isGlobal:1'              = 0
                'isMain:1'                = 0
                'isSilent:1'              = 0
                'lockedProgress:1'        = 0
                'name:8'                  = (Fmt $q.Name)
                'particle_count:3'        = -1
                'partySingleReward:1'     = 0
                'questLogic:8'            = 'AND'
                'repeatTime:3'            = -1
                'repeat_relative:1'       = 1
                'simultaneous:1'          = 0
                'snd_complete:8'          = 'random.levelup'
                'snd_update:8'            = 'random.levelup'
                'taskLogic:8'             = 'AND'
                'visibility:8'            = 'NORMAL'
            }
        }
        'questIDHigh:4'   = $HIGH
        'questIDLow:4'    = $q.Low
        'rewards:9'       = $rewards
        'tasks:9'         = [ordered]@{ '0:10' = $task }
    }
}

